import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
await mkdir('evidence/pointer',{recursive:true});
const browser=await chromium.launch({headless:true});
const report=[];
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000},locale:'zh-CN'});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('https://api.github.com/**',r=>r.fulfill({json:{}}));
  await page.goto('http://127.0.0.1:4173/');await page.waitForTimeout(750);
  const hero=page.locator('.hero');
  const box=await hero.boundingBox();
  await page.mouse.move(box.x+box.width*.8,box.y+box.height*.35);
  await page.waitForFunction(()=>document.querySelector('.hero').dataset.pointerSettling==='false');
  const first=await hero.evaluate(el=>({rx:el.style.getPropertyValue('--hero-rx'),ry:el.style.getPropertyValue('--hero-ry'),grid:el.style.getPropertyValue('--grid-x'),visual:getComputedStyle(el.querySelector('.hero-visual')).transform}));
  assert.ok(parseFloat(first.ry)>0);assert.ok(parseFloat(first.rx)>0);assert.ok(Math.abs(parseFloat(first.grid))<=4);
  await page.mouse.move(box.x+box.width*.2,box.y+box.height*.75,{steps:10});
  await page.waitForFunction(()=>document.querySelector('.hero').dataset.pointerSettling==='false');
  const second=await hero.evaluate(el=>({rx:el.style.getPropertyValue('--hero-rx'),ry:el.style.getPropertyValue('--hero-ry')}));
  assert.ok(parseFloat(second.ry)<0);assert.ok(parseFloat(second.rx)<0);
  await page.screenshot({path:'evidence/pointer/desktop-hero.png'});
  const settled=await hero.getAttribute('style');await page.waitForTimeout(180);assert.equal(await hero.getAttribute('style'),settled);
  await page.mouse.move(2,2);await page.waitForFunction(()=>!document.querySelector('.hero').style.getPropertyValue('--hero-rx'));
  for(const selector of ['.mode-jig','.feat-a','.wf-stage','.steps-v .step']) {
    const card=page.locator(selector).first();await card.evaluate(el=>el.scrollIntoView({block:'center',behavior:'instant'}));await page.waitForTimeout(700);
    await card.hover({position:{x:35,y:45}});
    await page.waitForFunction(selector=>document.querySelector(selector).dataset.pointerSettling==='false',selector);
    const a=await card.evaluate(el=>({x:el.style.getPropertyValue('--spot-x'),tilt:el.style.getPropertyValue('--tilt-y')}));
    assert.notEqual(a.x,'');assert.ok(Math.abs(parseFloat(a.tilt))<=1.3);
    const b=await card.boundingBox();await page.mouse.move(b.x+b.width*.8,b.y+b.height*.7,{steps:8});
    await page.waitForFunction(selector=>document.querySelector(selector).dataset.pointerSettling==='false',selector);
    const z=await card.evaluate(el=>({x:el.style.getPropertyValue('--spot-x'),tilt:el.style.getPropertyValue('--tilt-y')}));assert.notEqual(z.x,a.x);
    await card.screenshot({path:`evidence/pointer/${selector.replace(/[^a-z]/g,'')}.png`});
    await page.mouse.move(1,80);await page.waitForFunction(selector=>!document.querySelector(selector).hasAttribute('data-pointer-active')&&!document.querySelector(selector).style.getPropertyValue('--tilt-y'),selector);
  }
  await page.locator('.mode-jig').hover();await page.waitForTimeout(100);
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  assert.equal(await page.locator('[data-pointer-active]').count(),0);
  await page.emulateMedia({reducedMotion:'reduce'});await page.locator('.mode-jig').hover();
  assert.equal(await page.locator('[data-pointer-active]').count(),0);
  assert.equal(await page.locator('.mode-jig').evaluate(el=>getComputedStyle(el).transform),'none');
  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));await hero.hover();
  assert.equal(await hero.evaluate(el=>el.style.getPropertyValue('--hero-ry')),'');
  await page.emulateMedia({reducedMotion:'no-preference'});await hero.hover({position:{x:300,y:250}});
  await page.waitForFunction(()=>document.querySelector('.hero').dataset.pointerActive==='true');
  await page.locator('#modes').scrollIntoViewIfNeeded();await page.waitForFunction(()=>!document.querySelector('.hero').hasAttribute('data-pointer-active'));
  assert.deepEqual(errors,[]);report.push({desktop:'hero/card tracking, damping, settling, leave, blur, scroll, reduced motion and preference changes passed',errors});
  await page.close();
  const phone=await browser.newPage({viewport:{width:390,height:900},hasTouch:true,isMobile:true,locale:'zh-CN'});
  await phone.route('https://api.github.com/**',r=>r.fulfill({json:{}}));await phone.goto('http://127.0.0.1:4173/');await phone.waitForTimeout(750);
  assert.equal(await phone.evaluate(()=>matchMedia('(pointer: fine)').matches),false);
  await phone.locator('.hero').dispatchEvent('pointermove',{pointerType:'touch',clientX:200,clientY:300});
  assert.equal(await phone.locator('[data-pointer-active]').count(),0);
  assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  await phone.screenshot({path:'evidence/pointer/mobile-no-effects.png'});await phone.close();
  report.push({mobile:'touch input has no pointer effect or overflow'});
  await writeFile('evidence/pointer/report.json',JSON.stringify(report,null,2));console.log(report);
}finally{await browser.close();}
